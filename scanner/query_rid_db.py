def cmd_show(args):
    conn = get_db_connection(args.db)
    timeout_s = getattr(args, "timeout_s", 300.0)
    reconcile_stale_encounters(conn, timeout_s)

    query_str = """
        SELECT * FROM encounters 
        WHERE encounter_id = ? OR encounter_id LIKE ? 
           OR serial_number = ? OR serial_number LIKE ?
           OR mac = ? OR mac LIKE ?
        ORDER BY first_seen DESC LIMIT 1
    """
    row = conn.execute(query_str, (
        args.encounter_id, f"%{args.encounter_id}%",
        args.encounter_id, f"%{args.encounter_id}%",
        args.encounter_id, f"%{args.encounter_id}%"
    )).fetchone()

