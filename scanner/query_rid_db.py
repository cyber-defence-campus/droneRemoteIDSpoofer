def main():
    parser = argparse.ArgumentParser(
        description="Drone Remote ID SQLite Database Search, Inspection & Export Utility",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    parser.add_argument("--db", default="rid_detections.db", help="Path to SQLite database file")
    parser.add_argument("--timeout-s", "--timeout", dest="timeout_s", type=float, default=300.0,
                        help="Flight encounter silence timeout in seconds (default: 300s)")

    subparsers = parser.add_subparsers(dest="command", required=True, help="Command to execute")

    # Command: list
    p_list = subparsers.add_parser("list", help="List recorded drone flight encounters")
    p_list.add_argument("--mac", help="Filter by transmitter MAC address")
    p_list.add_argument("--serial", help="Filter by UAS Serial Number")
    p_list.add_argument("--since", help="Filter encounters starting after ISO date (e.g. 2026-08-25)")
    p_list.add_argument("--active-only", action="store_true", help="Only show currently active encounters")
    p_list.add_argument("--limit", type=int, default=50, help="Maximum encounters to show")

    # Command: show
    p_show = subparsers.add_parser("show", help="Show detailed breakdown of a flight encounter")
    p_show.add_argument("encounter_id", help="Encounter ID (e.g. ENC-20260825-141510-AABBCC)")

    # Command: export-geojson
    p_geojson = subparsers.add_parser("export-geojson", help="Export flight trajectory to RFC 7946 GeoJSON format")
    p_geojson.add_argument("encounter_id", help="Encounter ID to export")
    p_geojson.add_argument("-o", "--output", help="Output .geojson file path")

    # Command: export-csv
    p_csv = subparsers.add_parser("export-csv", help="Export flight trajectory points to CSV")
    p_csv.add_argument("encounter_id", help="Encounter ID to export")
    p_csv.add_argument("-o", "--output", help="Output .csv file path")

    # Command: stats
    subparsers.add_parser("stats", help="Show global database statistics and summary")

    args = parser.parse_args()

    if args.command == "list":
        cmd_list(args)
    elif args.command == "show":
        cmd_show(args)
    elif args.command == "export-geojson":
        cmd_export_geojson(args)
    elif args.command == "export-csv":
        cmd_export_csv(args)
    elif args.command == "stats":
        cmd_stats(args)


if __name__ == "__main__":
    main()
