def cmd_list(args):
    conn = get_db_connection(args.db)
    timeout_s = getattr(args, "timeout_s", 300.0)
    reconcile_stale_encounters(conn, timeout_s)

    query = "SELECT * FROM encounters WHERE 1=1"
    params = []

    if args.mac:
        query += " AND mac LIKE ?"
        params.append(f"%{args.mac}%")
    if args.serial:
        query += " AND serial_number LIKE ?"
        params.append(f"%{args.serial}%")
    if args.active_only:
        query += " AND is_active = 1"
    if args.since:
        try:
            dt = datetime.fromisoformat(args.since).timestamp()
            query += " AND first_seen >= ?"
            params.append(dt)
        except Exception:
            print(f"{C_RED}[-] Error: Invalid date format for --since (use ISO format, e.g. 2026-08-25).{C_RESET}")
            sys.exit(1)

    query += " ORDER BY first_seen DESC"
    if args.limit:
        query += f" LIMIT {args.limit}"

    rows = conn.execute(query, params).fetchall()

    if not rows:
        print(f"{C_YELLOW}[*] No flight encounters found matching criteria in {args.db}.{C_RESET}")
        return

    print(f"\n{C_BOLD}{C_CYAN}🚁 RECORDED DRONE FLIGHT ENCOUNTERS ({len(rows)} found){C_RESET}")
    print(f"{C_GRAY}Database: {args.db}{C_RESET}\n")

    # Header
    hdr = f"{'ENCOUNTER ID':<26} {'START TIME (UTC)':<19} {'DURATION':<10} {'PKTS':<6} {'MAC':<18} {'SERIAL / UAS ID':<22} {'TRANSPORTS':<14} {'MAX ALT':<9} {'STATUS':<8}"
    print(f"{C_BOLD}{hdr}{C_RESET}")
    print(f"{C_GRAY}{'-'*len(hdr)}{C_RESET}")

    now = time.time()
    for r in rows:
        enc_id = r["encounter_id"]
        start_str = r["first_seen_iso"][:19].replace("T", " ")
        dur_str = format_duration(r["duration_s"])
        pkts = r["packet_count"]
        mac = r["mac"]
        serial = r["serial_number"] or f"{C_GRAY}<None>{C_RESET}"
        transports = r["transports"]
        max_alt = f"{r['max_alt_m']:.1f}m" if r["max_alt_m"] is not None else f"{C_GRAY}-{C_RESET}"
        is_active = bool(r["is_active"] and (now - r["last_seen"] <= timeout_s))
        status = f"{C_GREEN}ACTIVE{C_RESET}" if is_active else f"{C_GRAY}CLOSED{C_RESET}"

        print(f"{C_WHITE}{enc_id:<26}{C_RESET} {start_str:<19} {dur_str:<10} {pkts:<6} {mac:<18} {serial:<22} {transports:<14} {max_alt:<9} {status:<8}")

    print(f"{C_GRAY}{'-'*len(hdr)}{C_RESET}\n")


