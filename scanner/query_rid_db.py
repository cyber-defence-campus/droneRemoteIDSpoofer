    print(f"  • {C_BOLD}Total Packets    :{C_RESET} {row['packet_count']}")
    print(f"  • {C_BOLD}Transports Used  :{C_RESET} {row['transports']}")
    print(f"  • {C_BOLD}Channels Active  :{C_RESET} {row['channels']}")

