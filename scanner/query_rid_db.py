# ANSI Formatting
C_RESET = "\033[0m"
C_BOLD = "\033[1m"
C_RED = "\033[91m"
C_GREEN = "\033[92m"
C_YELLOW = "\033[93m"
C_BLUE = "\033[94m"
C_MAGENTA = "\033[95m"
C_CYAN = "\033[96m"
C_WHITE = "\033[97m"
C_GRAY = "\033[90m"


def format_duration(seconds: float) -> str:
    """Format duration in seconds into human-readable string (e.g. 3m 42s)."""
    secs = int(round(seconds))
    if secs < 60:
        return f"{secs}s"
    mins = secs // 60
    rem_secs = secs % 60
    if mins < 60:
        return f"{mins}m {rem_secs:02d}s"
    hours = mins // 60
    rem_mins = mins % 60
    return f"{hours}h {rem_mins:02d}m"


def get_db_connection(db_path: str) -> sqlite3.Connection:
    if not os.path.exists(db_path):
        print(f"{C_RED}[-] Error: Database file '{db_path}' does not exist.{C_RESET}")
        sys.exit(1)
    conn = sqlite3.connect(db_path, timeout=10.0)
    conn.row_factory = sqlite3.Row
    return conn


def reconcile_stale_encounters(conn: sqlite3.Connection, timeout_s: float = 300.0):
    """Marks any encounters that have exceeded the silence timeout as is_active = 0 in SQLite."""
    try:
        now = time.time()
        conn.execute("UPDATE encounters SET is_active = 0 WHERE is_active = 1 AND (? - last_seen) > ?;",
                     (now, timeout_s))
        conn.commit()
    except Exception:
        pass


