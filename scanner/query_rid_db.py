def cmd_export_geojson(args):
    conn = get_db_connection(args.db)
    query_str = """
        SELECT * FROM encounters 
        WHERE encounter_id = ? OR encounter_id LIKE ? 
           OR serial_number = ? OR serial_number LIKE ?
           OR mac = ? OR mac LIKE ?
        ORDER BY first_seen DESC LIMIT 1
    """
    row = conn.execute(query_str, (
        args.encounter_id, f"%{args.encounter_id}%",
        args.encounter_id, f"%{args.encounter_id}%",
        args.encounter_id, f"%{args.encounter_id}%"
    )).fetchone()

    if not row:
        print(f"{C_RED}[-] Error: Encounter '{args.encounter_id}' not found in {args.db}.{C_RESET}")
        sys.exit(1)

    traj = json.loads(row["trajectory_json"]) if row["trajectory_json"] else []
    if not traj:
        print(f"{C_YELLOW}[!] Warning: Encounter '{row['encounter_id']}' contains no geographic trajectory points.{C_RESET}")
        return

    features = []

    # 1. Flight LineString Feature (GeoJSON coordinates are [lon, lat, alt])
    line_coords = [[pt[1], pt[0], pt[2] if pt[2] is not None else 0.0] for pt in traj]
    flight_feature = {
        "type": "Feature",
        "properties": {
            "encounter_id": row["encounter_id"],
            "mac": row["mac"],
            "serial_number": row["serial_number"],
            "operator_id": row["operator_id"],
            "first_seen": row["first_seen_iso"],
            "last_seen": row["last_seen_iso"],
            "duration_s": row["duration_s"],
            "packet_count": row["packet_count"],
            "max_speed_mps": row["max_speed_mps"],
            "max_alt_m": row["max_alt_m"],
            "stroke": "#00ff88",
            "stroke-width": 4
        },
        "geometry": {
            "type": "LineString",
            "coordinates": line_coords
        }
    }
    features.append(flight_feature)

    # 2. Start and End Position Points
    start_pt = {
        "type": "Feature",
        "properties": {
            "name": f"Flight Start: {row['encounter_id']}",
            "timestamp": row["first_seen_iso"],
            "marker-color": "#0088ff",
            "marker-symbol": "airport"
        },
        "geometry": {
            "type": "Point",
            "coordinates": [traj[0][1], traj[0][0], traj[0][2] if traj[0][2] is not None else 0.0]
        }
    }
    features.append(start_pt)

    if len(traj) > 1:
        end_pt = {
            "type": "Feature",
            "properties": {
                "name": f"Flight End: {row['encounter_id']}",
                "timestamp": row["last_seen_iso"],
                "marker-color": "#ff3333",
                "marker-symbol": "land"
            },
            "geometry": {
                "type": "Point",
                "coordinates": [traj[-1][1], traj[-1][0], traj[-1][2] if traj[-1][2] is not None else 0.0]
            }
        }
        features.append(end_pt)

    # 3. Pilot / Home Position Point if available
    if row["pilot_lat"] is not None and row["pilot_lon"] is not None:
        pilot_pt = {
            "type": "Feature",
            "properties": {
                "name": f"Pilot / Operator Location ({row['operator_id'] or 'Unknown'})",
                "marker-color": "#ffaa00",
                "marker-symbol": "heliport"
            },
            "geometry": {
                "type": "Point",
                "coordinates": [row["pilot_lon"], row["pilot_lat"], row["pilot_alt_m"] if row["pilot_alt_m"] is not None else 0.0]
            }
        }
        features.append(pilot_pt)

    geojson_doc = {
        "type": "FeatureCollection",
        "features": features
    }

    out_path = args.output or f"{row['encounter_id']}.geojson"
    with open(out_path, "w") as f:
        json.dump(geojson_doc, f, indent=2)

    print(f"{C_GREEN}[+] Successfully exported GeoJSON trajectory ({len(traj)} points) to {out_path}{C_RESET}")
    print(f"{C_GRAY}    Tip: Drag and drop {out_path} into https://geojson.io to visualize the flight track!{C_RESET}")


